#!/bin/sh
# ci-orand.sh: print every line with an ungrouped A || B && C (SH-CI-30) in YAML, sh, bash and bats files.
# Skipped: lines with GitHub expressions or if:/runs-on: keys, "||" inside [[ ]], and files with a
# generated-file marker. The pattern is a reading aid, a hit is a line to read.
# Exit: 0 clean, 1 finding, 69 tool missing, 78 not a git work tree.
set -u
for t in git xargs awk; do
    command -v "$t" >/dev/null 2>&1 || {
        echo "ci-orand: $t missing" >&2
        exit 69
    }
done
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || {
    echo "ci-orand: not a git work tree" >&2
    exit 78
}
# shellcheck disable=SC2016 # single quotes are deliberate: the $ is for awk, not the shell
out=$(git ls-files -z --cached --others --exclude-standard -- '*.yml' '*.yaml' '*.sh' '*.bash' '*.bats' | xargs -0 -r awk '
function dbl(l,   s, i, j, seg) {
    s = l
    while ((i = index(s, "[[")) > 0) {
        s = substr(s, i + 2); j = index(s, "]]")
        seg = j ? substr(s, 1, j - 1) : s
        if (seg ~ / [|][|] /) return 1
    }
    return 0
}
function finish(   i) {
    if (!gen) for (i = 1; i <= nheld; i++) print held[i]
    nheld = 0
}
FNR == 1 { if (NR > 1) finish(); cur = FILENAME; gen = 0 }
{
    line = $0; sub(/\r$/, "", line)
    if (tolower(line) ~ /^# .*(do not edit|automatically generated|autogenerated|auto-generated)/) gen = 1
    if (line !~ / [|][|] /) next
    if (line ~ /^[ \t]*(-[ \t]+)?(if|runs-on):/) next
    if (line ~ /github\.(event|ref|sha|actor|repository|head_ref|run_id|workspace)/ || line ~ /(^|[^A-Za-z0-9_])(inputs|matrix|needs|steps|secrets|vars)\.[A-Za-z_]/) next
    if (dbl(line)) next
    if (line ~ / [|][|] ([^]|&;(){}`[]|\$\([^)]*\)|[0-9]?>&[0-9])+ && /) held[++nheld] = cur ":" FNR ": " line
}
END { finish() }
')
[ -z "$out" ] && exit 0
printf '%s\n' "$out"
exit 1
