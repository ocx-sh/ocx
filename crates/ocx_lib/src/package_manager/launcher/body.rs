    // ── Byte-exact golden tests (One-Way Door wire-vocabulary) ─────────────

    /// ADR §6 invariant — no `_target` baked. The launcher passes its OWN
    /// filename via `${0##*/}` as argv0 after `--`, then forwards `"$@"` for
    /// user args. `ocx launcher exec` resolves the binary via the package's
    /// PATH env (set up from metadata).
    ///
    /// **This golden flipped in WP-6 (D-V3)**: the argv0 form moved from
    /// `$(basename "$0")` to `${0##*/}`. Intended, not a regression — see the
    /// module docs for why the fork-and-lookup form was retired.
    #[test]
    fn unix_launcher_body_byte_exact_match_adr_form() {
        let body = super::unix_launcher_body(&safe("/some/pkg/root"));
        // The stable wire surface is: `launcher exec '<pkg_root>' --` pair.
        // `${OCX_BINARY_PIN:-ocx}` is the pin expression (renamed from OCX_BINARY).
        let expected = "#!/bin/sh\n\
                        # Generated by ocx at install time. Do not edit.\n\
                        exec \"${OCX_BINARY_PIN:-ocx}\" launcher exec '/some/pkg/root' -- \"${0##*/}\" \"$@\"\n";
        assert_eq!(
            body, expected,
            "Unix launcher must match the byte-exact form (launcher exec subcommand; OCX_BINARY_PIN pin; no file://; no --self baked; no presentation flags baked)",
        );
    }

