#!/bin/sh
# ci-taint.sh MODE: print every run-body line that pastes an attacker-reachable ${{ }} expression.
# Modes: inputs (SH-CI-07), envctx (SH-CI-08), outputs (SH-CI-23), matrix (SH-CI-24).
# Files come from git: top-level workflow files and every action.yml. Files that carry a generated-file
# marker are skipped for outputs and matrix (fix the generator). A "key: value" line other than run: is skipped.
# Exit: 0 clean, 1 finding, 64 bad mode, 69 tool missing, 78 not a git work tree.
set -u
mode=${1:-}
case $mode in
    inputs | envctx | outputs | matrix) ;;
    *)
        echo "usage: ci-taint.sh inputs|envctx|outputs|matrix" >&2
        exit 64
        ;;
esac
for t in git xargs awk; do
    command -v "$t" >/dev/null 2>&1 || {
        echo "ci-taint: $t missing" >&2
        exit 69
    }
done
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || {
    echo "ci-taint: not a git work tree" >&2
    exit 78
}
# shellcheck disable=SC2016 # single quotes are deliberate: the $ is for awk, not the shell
out=$(git ls-files -z --cached --others --exclude-standard -- ':(glob).github/workflow[s]/*.yml' ':(glob).github/workflow[s]/*.yaml' ':(glob)**/action.yml' ':(glob)**/action.yaml' | xargs -0 -r awk -v mode="$mode" '
function ind(s) { match(s, /^ */); return RLENGTH }
function skipkey(l,   t, k) {
    t = l; sub(/^[ ]*(-[ ]+)?/, "", t)
    if (t !~ /^[A-Za-z_][A-Za-z0-9_.-]*:([ \t]|$)/) return 0
    k = t; sub(/:.*/, "", k)
    return k != "run"
}
function tainted(e) {
    if (mode == "inputs") return e ~ /[^A-Za-z0-9_]inputs\./ || e ~ /(^|[^A-Za-z0-9_])github\.(head_ref|ref_name)([^A-Za-z0-9_]|$)/ || e ~ /(^|[^A-Za-z0-9_])github\.event\.(pages|client_payload)\./ || e ~ /(^|[^A-Za-z0-9_])github\.event\.[A-Za-z0-9_.*]*\.(title|body|message|name|full_name|email|ref|label|default_branch)([^A-Za-z0-9_]|$)/
    if (mode == "envctx") return e ~ /^[ ]*env\./
    if (mode == "outputs") return e ~ /(^|[^A-Za-z0-9_])(steps|needs)\.[A-Za-z0-9_-]+\.outputs([^A-Za-z0-9_]|$)/
    return e ~ /(^|[^A-Za-z0-9_])matrix\./
}
function hit(l,   rest, i, j, e) {
    rest = l
    while ((i = index(rest, "${{")) > 0) {
        rest = substr(rest, i + 3); j = index(rest, "}}")
        if (j == 0) { e = rest; rest = "" } else { e = substr(rest, 1, j - 1); rest = substr(rest, j + 2) }
        if (tainted(" " e " ")) return 1
    }
    return 0
}
function dynctx(s) { return s ~ /(needs|steps|github\.event|inputs)\./ }
function finish(   i) {
    if (mode == "matrix" && !dyn) nheld = 0
    if (gen && (mode == "outputs" || mode == "matrix")) nheld = 0
    for (i = 1; i <= nheld; i++) print held[i]
    nheld = 0
}
FNR == 1 { if (NR > 1) finish(); cur = FILENAME; gen = dyn = inmx = 0 }
{
    line = $0; sub(/\r$/, "", line)
    low = tolower(line)
    if (low ~ /^# .*(do not edit|automatically generated|autogenerated|auto-generated)/) gen = 1
    if (line ~ /^[ \t]*$/) next
    n = ind(line)
    if (inmx && n <= mxi) inmx = 0
    if (inmx && low ~ /^[ ]*(([A-Za-z0-9_-]+:[ ]*)|(-[ ]+))\$\{\{[ ]*(fromjson\([ (]*)?(needs|steps|github\.event|inputs)\./) dyn = 1
    if (line ~ /^[ ]*(-[ ]+)?matrix:/) {
        v = line; sub(/^[ ]*(-[ ]+)?matrix:[ ]*/, "", v)
        if (v ~ /^\$\{\{/ && dynctx(v)) dyn = 1
        else if (v == "" || v ~ /^#/) { inmx = 1; mxi = n }
    }
    if (skipkey(line)) next
    if (index(line, "${{") && hit(line)) held[++nheld] = cur ":" FNR ": " line
}
END { finish() }
')
[ -z "$out" ] && exit 0
printf '%s\n' "$out"
exit 1
