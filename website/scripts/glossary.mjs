// Renders `src/content/docs/reference/glossary.md` from `src/data/glossary.json`.
//
//   node scripts/glossary.mjs          write the page
//   node scripts/glossary.mjs --check  exit 1 when the committed page differs from the data

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { glossaryMarkdown } from '@ocx-sh/theme/glossary';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = join(ROOT, 'src', 'content', 'docs');
export const PAGE = join(DOCS, 'reference', 'glossary.md');
const DATA = join(ROOT, 'src', 'data', 'glossary.json');

// Section order and headings; a category missing here sorts after these, by slug.
const CATEGORIES = {
  ocx: 'Packages and storage',
  oci: 'OCI and registries',
  platform: 'Platforms',
  index: 'Indices',
  project: 'Projects',
  env: 'Environments',
  config: 'Configuration',
  shell: 'Shell',
  publishing: 'Publishing',
  signing: 'Signing',
  security: 'Security',
  interface: 'Machine interface',
};

/** Route (`explanation/storage/`) to page title, read from each page's front matter. */
function titles() {
  const out = {};
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, e.name);
      if (e.isDirectory()) walk(path);
      else if (/\.mdx?$/.test(e.name)) {
        const title = /^title:\s*"?([^"\n]+?)"?\s*$/m.exec(readFileSync(path, 'utf8').split('\n---')[0]);
        const route = path.slice(DOCS.length + 1).replace(/\.mdx?$/, '').replace(/(^|\/)index$/, '');
        if (title) out[route ? `${route}/` : ''] = title[1];
      }
    }
  };
  walk(DOCS);
  return out;
}

/** The whole page: front matter, declaration, then the entries. */
export function render() {
  const terms = JSON.parse(readFileSync(DATA, 'utf8'));
  const body = glossaryMarkdown(terms, { categories: CATEGORIES, base: '/docs/', titles: titles() });
  return `---\ntitle: "Glossary"\n---\n<!-- doc_type: reference -->\n<!-- Generated by website/scripts/glossary.mjs from src/data/glossary.json: edit the data, run \`task website:glossary:generate\`. -->\n\n${body}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const page = render();
  if (process.argv.includes('--check')) {
    if (!existsSync(PAGE) || readFileSync(PAGE, 'utf8') !== page) {
      console.error('glossary:check: reference/glossary.md differs from src/data/glossary.json; run `task website:glossary:generate`');
      process.exit(1);
    }
  } else writeFileSync(PAGE, page);
}
